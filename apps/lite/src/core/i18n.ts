const DICT: Record<Lang, Record<MsgKey, string>> = { ru, kk, en };

export type T = (k: MsgKey) => string;

export function t(k: MsgKey): string {
  return DICT[getSettings().lang]?.[k] ?? ru[k];
}

export function useT(): T {
  const { lang } = useSettings();
  return (k) => DICT[lang]?.[k] ?? ru[k];
}

/** "1:02:03" / "4:05". */
export function clock(sec: number): string {
  if (!isFinite(sec) || sec < 0) sec = 0;
  const s = Math.floor(sec % 60);
  const m = Math.floor((sec / 60) % 60);
  const h = Math.floor(sec / 3600);
  const pad = (n: number) => (n < 10 ? "0" + n : String(n));
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/** "2 ч 16 мин" / "2h 16m". */
export function runtime(min: number | undefined, lang: Lang): string {
  if (!min) return "";
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (lang === "en") return h ? `${h}h ${m}m` : `${m}m`;
  if (lang === "kk") return h ? `${h} сағ ${m} мин` : `${m} мин`;
  return h ? `${h} ч ${m} мин` : `${m} мин`;
}

/** "1 сезон / 3 сезона / 10 сезонов", "10 маусым", "10 seasons". */
export function seasonsCount(n: number, lang: Lang): string {
  if (lang === "en") return `${n} season${n === 1 ? "" : "s"}`;
  if (lang === "kk") return `${n} маусым`;
  const m10 = n % 10;
  const m100 = n % 100;
  const w = m10 === 1 && m100 !== 11 ? "сезон" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "сезона" : "сезонов";
  return `${n} ${w}`;
}
