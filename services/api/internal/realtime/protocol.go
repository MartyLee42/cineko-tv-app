// Package realtime runs the WebSocket hub at /api/v1/ws: device presence,
// state fan-out and phone→TV commands with acknowledgements.
package realtime

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"slices"
)

// Envelope is the single message shape in both directions.
type Envelope struct {
	ID             string          `json:"id,omitempty"`
	Type           string          `json:"type"`
	TargetDeviceID string          `json:"target_device_id,omitempty"`
	DeviceID       string          `json:"device_id,omitempty"`
	Payload        json.RawMessage `json:"payload,omitempty"`
	// From identifies who sent a command; set by the server, never trusted from clients.
	From *Sender `json:"from,omitempty"`
}

// Sender is stamped on commands forwarded to a TV.
type Sender struct {
	UserID      string `json:"user_id"`
	Username    string `json:"username"`
	DisplayName string `json:"display_name"`
}

// Client → server control messages.
const (
	TypeAuth = "auth" // {token}: first message for clients without a cookie
	TypePing = "ping"
	TypeAck  = "ack" // device → server reply to a command
	// TypeDeviceState is sent by the TV whenever its state changes. The TV
	// is the authority on playback state; the server only relays it.
	TypeDeviceState = "device.state"
)

// Server → client events.
const (
	TypeHello          = "hello"
	TypePong           = "pong"
	TypeError          = "error"
	TypeDevicePresence = "device.presence"
	TypeDeviceChanged  = "device.changed"
	// TypeMessage delivers an admin message (payload: Message) to users'
	// controllers and, when show_on_tv, to the TVs they own.
	TypeMessage = "message"
	// TypeAdminDevicesUpdated tells super_admins' browser sockets that the
	// Admin → Devices view changed (payload {reason}); throttled, data-free.
	TypeAdminDevicesUpdated = "admin.devices.updated"
)

// Commands a controller may send to a TV. Only device.* are executed in
// Phase 1; the TV answers the rest with an "unsupported" ack until Phase 3.
var Commands = []string{
	"media.open", "media.play", "media.pause", "media.resume", "media.stop",
	"media.seek", "media.next_episode", "media.select_source",
	"playback.set_audio", "playback.set_subtitles", "playback.set_volume",
	"device.show_message", "device.request_state",
	"iptv.play",
	"video.play",
}

func isCommand(t string) bool { return slices.Contains(Commands, t) }

// AckPayload is the result of a command.
type AckPayload struct {
	OK     bool            `json:"ok"`
	Error  string          `json:"error,omitempty"`
	Result json.RawMessage `json:"result,omitempty"`
}

// Error codes sent in acks generated by the server.
const (
	ErrDeviceOffline = "device_offline"
	ErrTimeout       = "timeout"
	ErrForbidden     = "forbidden"
	ErrBadMessage    = "bad_message"
	ErrBadPayload    = "bad_payload"
	ErrNotFound      = "not_found"
	ErrFailed        = "failed"
)

func newCommandID() string {
	var b [12]byte
	_, _ = rand.Read(b[:])
	return hex.EncodeToString(b[:])
}

func mustJSON(v any) json.RawMessage {
	b, _ := json.Marshal(v)
	return b
}
